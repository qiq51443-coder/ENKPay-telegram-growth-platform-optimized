import axios from 'axios';

const BASE_URL = import.meta.env.VITE_API_URL || '/api';

export const api = axios.create({
  baseURL: BASE_URL,
  timeout: 15000, // 15s: accommodates 15s SDK polling window + server processing time
});

// ─── Response interceptor ─────────────────────────────────────────────────────
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response?.status === 401) {
      console.warn('[API] 401 Unauthorized — initData may be invalid or expired');
    } else if (error.response?.status >= 500) {
      console.error('[API] Server error:', error.response?.status, error.response?.data);
    } else if (!error.response) {
      console.error('[API] Network error — no response received:', error.message);
    }
    return Promise.reject(error);
  }
);

// ─── Init data management ──────────────────────────────────────────────────────
export function setInitData(initData: string) {
  if (initData) {
    api.defaults.headers.common['X-Telegram-Init-Data'] = initData;
  }
}

// ─── Session token management ─────────────────────────────────────────────────
/**
 * Persist a session token (issued by /api/miniapp/bot-token/exchange) so that
 * all subsequent API requests authenticate via X-Session-Token instead of
 * re-validating initData HMAC on every request.
 */
export function setSessionToken(sessionToken: string) {
  if (sessionToken) {
    api.defaults.headers.common['X-Session-Token'] = sessionToken;
  }
}

// ─── Bot Token Exchange ───────────────────────────────────────────────────────
/**
 * Exchange the short-lived one-time token (generated by the bot and passed as
 * a URL query param `start_token`) for a 24-hour session token + canonical
 * user profile.  Passing `telegramId` enables the server-side fallback
 * recovery path when the token has already expired.
 */
export async function exchangeBotToken(token: string, telegramId?: number) {
  const body: Record<string, unknown> = { token };
  if (telegramId) body.telegram_id = telegramId;
  const response = await api.post('/miniapp/bot-token/exchange', body);
  return response.data;
}

