// ─── Auth Sync ────────────────────────────────────────────────────────────────
export async function authSync(initData: string) {
  const response = await api.post('/miniapp/auth-sync', {}, {
    headers: { 'X-Telegram-Init-Data': initData },
  });
  return response.data;
}

// ─── JT Token Auth (Phase 1 — bypasses initData HMAC) ────────────────────────
/**
 * Exchange a one-time ?jt= URL token for a session token + user profile.
 * Called immediately on Mini App mount, before Telegram SDK is ready.
 * The token was generated by the Bot on /start and stored in Redis.
 */
export async function jtAuth(jt: string) {
  const response = await api.post('/miniapp/jt-auth', { jt });
  return response.data;
}

