const router = express.Router();

/**
 * POST /api/miniapp/preregister
 * Called by the Bot on /start to pre-register or refresh user info.
 * Auth: X-Bot-Id header (must match an active bot in the DB).
 * Body: { telegram_id, first_name?, username?, language_code? }
 */
router.post('/preregister', async (req, res) => {
  try {
    const botId = req.headers['x-bot-id'] as string;
    if (!botId) return res.status(403).json({ error: 'Missing X-Bot-Id header' });

    // Verify bot is active
    const botResult = await query(
      `SELECT id FROM bots WHERE id = $1 AND is_active = true LIMIT 1`,
      [botId]
    );
    if (botResult.rows.length === 0) {
      return res.status(403).json({ error: 'Bot not found or inactive' });
    }

    const { telegram_id, first_name, username, language_code } = req.body as {
      telegram_id?: number;
      first_name?: string;
      username?: string;
      language_code?: string;
    };
    if (!telegram_id || typeof telegram_id !== 'number') {
      return res.status(400).json({ error: 'telegram_id (number) is required' });
    }

    await upsertUserFromTelegramId(telegram_id, {
      firstName: first_name,
      username,
      languageCode: language_code,
    });

    return res.json({ success: true });
  } catch (err: any) {
    console.error('[miniapp/preregister] error:', err?.message);
    return res.status(500).json({ error: 'Internal server error' });
  }
});

/**
 * POST /api/miniapp/jt-store
 * Called by the Bot to store a jt token in Redis.
 * Auth: X-Bot-Id header.
 * Body: { jt, telegram_id, bot_id, first_name?, username?, language_code?, ttl? }
 */
router.post('/jt-store', async (req, res) => {
  try {
    const botId = req.headers['x-bot-id'] as string;
    if (!botId) return res.status(403).json({ error: 'Missing X-Bot-Id header' });

    const botResult = await query(
      `SELECT id FROM bots WHERE id = $1 AND is_active = true LIMIT 1`,
      [botId]
    );
    if (botResult.rows.length === 0) {
      return res.status(403).json({ error: 'Bot not found or inactive' });
    }

    const { jt, telegram_id, bot_id, first_name, username, language_code, ttl } = req.body as {
      jt?: string;
      telegram_id?: number;
      bot_id?: string;
      first_name?: string;
      username?: string;
      language_code?: string;
      ttl?: number;
    };

    if (!jt || typeof jt !== 'string' || jt.length !== 64) {
      return res.status(400).json({ error: 'jt must be a 64-char hex string' });
    }
    if (!telegram_id || typeof telegram_id !== 'number') {
      return res.status(400).json({ error: 'telegram_id (number) is required' });
    }

    const tokenTtl = typeof ttl === 'number' && ttl > 0 ? Math.min(ttl, 86400) : 86400;

    await setCache(
      jtTokenKey(jt),
      {
        telegramId: telegram_id,
        botId: bot_id || botId,
        firstName: first_name || '',
        username: username || null,
        languageCode: language_code || 'zh',
      },
      tokenTtl
    );

    return res.json({ success: true });
  } catch (err: any) {
    console.error('[miniapp/jt-store] error:', err?.message);
    return res.status(500).json({ error: 'Internal server error' });
  }
});

/**
 * POST /api/miniapp/jt-auth
 * Exchange a ?jt= URL token (generated by the Bot on /start) for a
 * session token + canonical user profile.
 * No Telegram initData or HMAC required — the token itself is the credential.
 * The token uses a sliding-window TTL: after each successful use the TTL is
 * reset to JT_SLIDING_WINDOW_TTL_SECONDS, allowing Telegram's cached WebApp URL
 * to be reopened within that window without requiring the user to go back to
 * the Bot.
 */
const JT_SLIDING_WINDOW_TTL_SECONDS = 86400; // 24 hours
router.post('/jt-auth', async (req, res) => {
  try {
    const { jt } = req.body as { jt?: string };
    if (!jt || typeof jt !== 'string' || jt.length !== 64) {
      return res.status(400).json({ error: 'jt token is required' });
    }

    const key = jtTokenKey(jt);
    const payload = await getCache<{
      telegramId: number;
      botId: string;
      firstName?: string;
      username?: string;
      languageCode?: string;
    }>(key);

    if (!payload?.telegramId) {
      return res.status(401).json({ error: 'Token invalid or expired', code: 'JT_INVALID' });
    }

    // Sliding-window: reset TTL to JT_SLIDING_WINDOW_TTL_SECONDS instead of deleting immediately.
    // This allows Telegram's cached WebApp URL to be reopened within the window
    // without requiring the user to restart the Bot.
    await setCache(key, payload, JT_SLIDING_WINDOW_TTL_SECONDS);

    const { telegramId, botId, firstName, username, languageCode } = payload;

    // Upsert user with the real info the Bot captured
    await upsertUserFromTelegramId(telegramId, {
      firstName: firstName || '',
      username: username || undefined,
      languageCode: languageCode || 'zh',
    });

    const userProfile = await buildCanonicalProfile(telegramId);
    if (!userProfile) {
      return res.status(404).json({ error: 'User not found after upsert' });
    }

    // Mint a 24-hour session token
    const sessionToken = crypto.randomBytes(32).toString('hex');
    await setCache(
      sessionTokenKey(sessionToken),
      { telegramId, botId },
      86400
    );

    console.info(`[miniapp/jt-auth] Success for telegramId=${telegramId} botId=${botId}`);

    return res.json({
      success: true,
      user: userProfile,
      session_token: sessionToken,
    });
  } catch (err: any) {
    console.error('[miniapp/jt-auth] error:', err?.message);
    return res.status(500).json({ error: 'Internal server error' });
  }
});

