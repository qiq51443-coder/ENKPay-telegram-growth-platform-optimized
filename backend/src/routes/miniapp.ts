/**
 * GET /api/miniapp/transactions
 * Get current user's transaction history from transfer_records, deposit_records,
 * withdrawal_records, and trading_orders (UNION query).
 */
router.get('/transactions', authenticateMiniApp, async (req: MiniAppAuthRequest, res) => {
  try {
    const telegramId = req.telegramUser?.id;
    if (!telegramId) return res.status(401).json({ error: 'Unauthorized' });

    // Use canonical user id for consistent cross-bot query (ORDER BY + LIMIT 1 prevents
    // returning a random row when legacy duplicate telegram_id records exist)
    const userResult = await query(
      `SELECT id FROM users WHERE telegram_id = $1 ORDER BY created_at ASC LIMIT 1`,
      [telegramId]
    );
    if (userResult.rows.length === 0) return res.status(404).json({ error: 'User not found' });
    const userId = userResult.rows[0].id;

    const parsedLimit = parseInt(String(req.query.limit ?? '50'), 10);
    const limitNum = isNaN(parsedLimit) || parsedLimit <= 0 ? 50 : Math.min(parsedLimit, 200);

    const result = await query(
      `SELECT id, type, amount, status, created_at, description, order_id
       FROM (
         -- Incoming transfers
         SELECT id::text, 'transfer_in' AS type, amount::numeric, status,
                created_at, NULL AS description, order_id
         FROM transfer_records
         WHERE to_user_id = $1

         UNION ALL

         -- Outgoing transfers
         SELECT id::text, 'transfer_out' AS type, amount::numeric, status,
                created_at, NULL AS description, order_id
         FROM transfer_records
         WHERE from_user_id = $1

         UNION ALL

         -- Deposits
         SELECT id::text, 'deposit' AS type, amount::numeric, status,
                created_at, tx_hash AS description, NULL AS order_id
         FROM deposit_records
         WHERE user_id = $1

         UNION ALL

         -- Withdrawals
         SELECT id::text, 'withdrawal' AS type, amount::numeric, status,
                created_at, to_address AS description, order_id
         FROM withdrawal_records
         WHERE user_id = $1

         UNION ALL

         -- Trading orders (instant trades)
         SELECT id::text,
                CASE WHEN profit >= 0 THEN 'trade_win' ELSE 'trade_loss' END AS type,
                CASE WHEN profit >= 0 THEN (amount * odds)::numeric ELSE amount::numeric END AS amount,
                status,
                created_at, pair_id::text AS description, NULL AS order_id
         FROM trading_orders
         WHERE user_id = $1

         UNION ALL

         -- Other transaction types from ledger (product, auction, rewards, etc.)
         -- Excludes types already fetched from their dedicated tables above:
         --   transfer_in/out → transfer_records
         --   deposit         → deposit_records
         --   withdrawal      → withdrawal_records
         --   trade_win/loss  → trading_orders
         SELECT id::text,
                type,
                ABS(amount)::numeric,
                'completed' AS status,
                created_at,
                description,
                reference_id::text AS order_id
         FROM transactions
         WHERE user_id = $1
           AND type NOT IN (
             'transfer_in','transfer_out','deposit','withdrawal','trade_win','trade_loss'
           )
       ) AS combined
       ORDER BY created_at DESC
       LIMIT $2`,
      [userId, limitNum]
    );

    res.json({ success: true, transactions: result.rows });
  } catch (error: any) {
    console.error('Miniapp transactions error:', error);
    res.status(500).json({ error: error.message });
  }
});

